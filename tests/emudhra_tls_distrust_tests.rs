fn parse_pem_chain(pem: &str) -> Vec<CertificateDer<'static>> {
    let mut certs = Vec::new();
    let mut in_cert = false;
    let mut b64 = String::new();
    for line in pem.lines() {
        let trimmed = line.trim();
        if trimmed == "-----BEGIN CERTIFICATE-----" {
            in_cert = true;
            b64.clear();
        } else if trimmed == "-----END CERTIFICATE-----" {
            in_cert = false;
            let der = base64::engine::general_purpose::STANDARD
                .decode(&b64)
                .expect("valid base64 PEM certificate");
            certs.push(CertificateDer::from(der));
        } else if in_cert {
            b64.push_str(trimmed);
        }
    }
    assert!(
        certs.len() >= 2,
        "expected leaf + at least 1 intermediate certificate"
    );
    certs
}

#[test]
fn all_twelve_compromised_emudhra_chains_are_rejected_as_distrusted() {
    let trust_anchors: &[TrustAnchor<'_>] = webpki_roots::TLS_SERVER_ROOTS;
    let time = UnixTime::since_unix_epoch(Duration::from_secs(VALIDATION_TIME_SECS));

    for case in COMPROMISED_CHAINS {
        let certs = parse_pem_chain(case.pem_chain);
        let ee = webpki::EndEntityCert::try_from(&certs[0]).expect("valid leaf DER");
        let intermediates = &certs[1..];

        let verify_res = ee.verify_for_usage(
            webpki::ALL_VERIFICATION_ALGS,
            trust_anchors,
            intermediates,
            time,
            webpki::KeyUsage::server_auth(),
            None,
            None,
        );

        assert_eq!(
            verify_res.err(),
            Some(webpki::Error::CertDistrusted),
            "compromised eMudhra chain for host '{}' ({} -> {}) MUST be rejected with CertDistrusted",
            case.host,
            case.intermediate_label,
            case.root_label,
        );

        // Also ensure hostname verification cannot bypass chain rejection.
        let server_name = ServerName::try_from(case.host).expect("valid DNS name");
        assert!(
            ee.verify_is_valid_for_subject_name(&server_name).is_ok(),
            "test fixture sanity check: leaf cert matches host {}",
            case.host
        );
    }
}

#[test]
fn webpki_roots_excludes_compromised_emsign_ecc_root_ca_g3() {
    // DER subject of "CN=emSign ECC Root CA - G3, O=eMudhra Technologies Limited, OU=emSign PKI, C=IN"
    let needle = b"emSign ECC Root CA - G3";
    for anchor in webpki_roots::TLS_SERVER_ROOTS {
        let subject_bytes = anchor.subject.as_ref();
        assert!(
            !subject_bytes.windows(needle.len()).any(|w| w == needle),
            "webpki_roots::TLS_SERVER_ROOTS must not contain 'emSign ECC Root CA - G3'"
        );
    }
}
